// Host-side guard for cpp/SsFrameData.hpp.
//
// `SsFrameData.hpp` reads the FrameData FlatBuffer by hand-written offsets so
// the shipped package needs no flatbuffers dependency. This program is what
// keeps those offsets honest: it drives a real `.ssab` through the Brain and,
// for every frame, compares each field the hand-rolled reader returns against
// the flatc-generated accessors for the same buffer.
//
// `30_core/30_render_loop.md` §2 asks for exactly this shape of check — a
// roundtrip comparison rather than a size assert, because a reordering of two
// same-size fields would sail past a size check.
//
// Build and run: tools/check-framedata.sh

#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>
#include <vector>

#include "framedata_generated.h"  // flatc output, generated by check-framedata.sh

#include "../packages/react-native-spritestudio/cpp/SsBaker.hpp"
#include "../packages/react-native-spritestudio/cpp/SsFrameData.hpp"

extern "C" {
void* ss_resource_create_copy(const unsigned char* ptr, size_t len);
void ss_resource_destroy(void* resource);
void* ss_runtime_create(void);
void ss_runtime_destroy(void* context);
bool ss_runtime_bind_resource(void* context, void* resource);
bool ss_runtime_setup_animation(void* context, const char* name);
void ss_runtime_set_render_mode(void* context, uint8_t mode);
float ss_runtime_update(void* context, float delta);
void ss_runtime_get_frame_data(void* context, float frame_no, unsigned char** out_data,
                               size_t* out_len);
void ss_runtime_get_world_matrices(void* context, const float** out_data, size_t* out_len);
void ss_runtime_get_local_vertices(void* context, const float** out_data, size_t* out_len);
void ss_runtime_get_local_uvs(void* context, const float** out_data, size_t* out_len);
void ss_runtime_get_cell_meta(void* context, const float** out_data, size_t* out_len);
}

namespace {

int g_failures = 0;

void Fail(const char* what, long long got, long long want, int frame, int index) {
  if (g_failures < 20) {
    std::fprintf(stderr, "MISMATCH frame %d, %s[%d]: raw=%lld flatc=%lld\n", frame, what, index,
                 got, want);
  }
  ++g_failures;
}

std::vector<uint8_t> ReadFile(const char* path) {
  std::FILE* f = std::fopen(path, "rb");
  if (f == nullptr) {
    std::fprintf(stderr, "cannot open %s\n", path);
    std::exit(2);
  }
  std::fseek(f, 0, SEEK_END);
  const long size = std::ftell(f);
  std::fseek(f, 0, SEEK_SET);
  std::vector<uint8_t> bytes(static_cast<size_t>(size));
  if (std::fread(bytes.data(), 1, bytes.size(), f) != bytes.size()) {
    std::fprintf(stderr, "short read on %s\n", path);
    std::exit(2);
  }
  std::fclose(f);
  return bytes;
}

/// Compares every field the raw reader exposes against flatc's accessors.
void CompareFrame(const sscore::FrameDataView& raw, const ss::runtime::FrameData* ref,
                  int frame) {
  const auto* refParts = ref->parts();
  const uint32_t refPartCount = refParts != nullptr ? refParts->size() : 0;
  if (raw.partCount() != refPartCount) {
    Fail("partCount", raw.partCount(), refPartCount, frame, 0);
    return;  // every per-part check below would just repeat this
  }
  for (uint32_t i = 0; i < refPartCount; ++i) {
    const auto* p = refParts->Get(i);
    // Bit-compare the floats: any difference at all is a layout bug, and a
    // tolerance would hide a field read one slot over that happens to be close.
    const float rawAlpha = raw.partAlpha(i);
    const float refAlpha = p->alpha();
    if (std::memcmp(&rawAlpha, &refAlpha, sizeof(float)) != 0) {
      Fail("partAlpha", static_cast<long long>(rawAlpha * 1e6f),
           static_cast<long long>(refAlpha * 1e6f), frame, static_cast<int>(i));
    }
    if (raw.partHidden(i) != p->hide()) {
      Fail("partHide", raw.partHidden(i), p->hide(), frame, static_cast<int>(i));
    }
  }

  const auto* refOrder = ref->draw_order();
  const uint32_t refOrderCount = refOrder != nullptr ? refOrder->size() : 0;
  if (raw.drawOrderCount() != refOrderCount) {
    Fail("drawOrderCount", raw.drawOrderCount(), refOrderCount, frame, 0);
  } else {
    for (uint32_t i = 0; i < refOrderCount; ++i) {
      if (raw.drawOrderAt(i) != refOrder->Get(i)) {
        Fail("drawOrder", raw.drawOrderAt(i), refOrder->Get(i), frame, static_cast<int>(i));
      }
    }
  }

  const auto* refBatches = ref->draw_batches();
  const uint32_t refBatchCount = refBatches != nullptr ? refBatches->size() : 0;
  if (raw.drawBatchCount() != refBatchCount) {
    Fail("drawBatchCount", raw.drawBatchCount(), refBatchCount, frame, 0);
    return;
  }
  for (uint32_t i = 0; i < refBatchCount; ++i) {
    const auto* b = refBatches->Get(i);
    const sscore::DrawBatchView v = raw.drawBatchAt(i);
    const int idx = static_cast<int>(i);
    if (v.startRank != b->start_rank()) Fail("batch.startRank", v.startRank, b->start_rank(), frame, idx);
    if (v.count != b->count()) Fail("batch.count", v.count, b->count(), frame, idx);
    if (v.textureHash != b->texture_hash()) Fail("batch.textureHash", v.textureHash, b->texture_hash(), frame, idx);
    if (v.vertexCount != b->vertex_count()) Fail("batch.vertexCount", v.vertexCount, b->vertex_count(), frame, idx);
    if (v.indexCount != b->index_count()) Fail("batch.indexCount", v.indexCount, b->index_count(), frame, idx);
    if (static_cast<uint8_t>(v.blendType) != static_cast<uint8_t>(b->blend_type()))
      Fail("batch.blendType", v.blendType, static_cast<uint8_t>(b->blend_type()), frame, idx);
    if (static_cast<uint8_t>(v.kind) != static_cast<uint8_t>(b->kind()))
      Fail("batch.kind", static_cast<uint8_t>(v.kind), static_cast<uint8_t>(b->kind()), frame, idx);
    if (v.flags != b->flags()) Fail("batch.flags", v.flags, b->flags(), frame, idx);
  }
}

}  // namespace

int main(int argc, char** argv) {
  if (argc < 3) {
    std::fprintf(stderr, "usage: ssbake_check <file.ssab> <animation> [frames]\n");
    return 2;
  }
  const char* ssabPath = argv[1];
  const char* animation = argv[2];
  const int frames = argc > 3 ? std::atoi(argv[3]) : 120;

  // Byte-layout assertions first: these catch a schema change without needing a
  // buffer to look at.
  static_assert(sizeof(ss::runtime::PartState) == sscore::PartStateLayout::kSize,
                "PartState size drifted from SsFrameData.hpp");
  static_assert(sizeof(ss::runtime::DrawBatch) == sscore::DrawBatchLayout::kSize,
                "DrawBatch size drifted from SsFrameData.hpp");

  const std::vector<uint8_t> ssab = ReadFile(ssabPath);
  void* resource = ss_resource_create_copy(ssab.data(), ssab.size());
  if (resource == nullptr) {
    std::fprintf(stderr, "ss_resource_create_copy failed for %s\n", ssabPath);
    return 1;
  }
  void* ctx = ss_runtime_create();
  if (!ss_runtime_bind_resource(ctx, resource)) {
    std::fprintf(stderr, "ss_runtime_bind_resource failed\n");
    return 1;
  }
  ss_runtime_set_render_mode(ctx, 0);  // RenderMode::Direct
  if (!ss_runtime_setup_animation(ctx, animation)) {
    std::fprintf(stderr, "ss_runtime_setup_animation('%s') failed\n", animation);
    return 1;
  }

  sscore::SsBaker baker;
  size_t maxVertices = 0;
  size_t maxBatches = 0;

  for (int frame = 0; frame < frames; ++frame) {
    const float frameNo = ss_runtime_update(ctx, 1.0f / 60.0f);

    unsigned char* fdPtr = nullptr;
    size_t fdLen = 0;
    ss_runtime_get_frame_data(ctx, frameNo, &fdPtr, &fdLen);
    if (fdPtr == nullptr || fdLen == 0) continue;

    const sscore::FrameDataView raw(fdPtr, fdLen);
    if (!raw.valid()) {
      std::fprintf(stderr, "frame %d: FrameDataView rejected a %zu byte buffer\n", frame, fdLen);
      ++g_failures;
      continue;
    }
    CompareFrame(raw, ss::runtime::GetFrameData(fdPtr), frame);

    // Exercise the baker on the same buffer so an out-of-bounds read shows up
    // here (under ASan) rather than on a device.
    sscore::SsSoAPointers soa;
    size_t len = 0;
    ss_runtime_get_world_matrices(ctx, &soa.worldMatrices, &len);
    soa.partCount = len / 16;
    ss_runtime_get_local_vertices(ctx, &soa.localVertices, &len);
    ss_runtime_get_local_uvs(ctx, &soa.localUvs, &len);
    ss_runtime_get_cell_meta(ctx, &soa.cellMeta, &len);
    baker.bake(raw, soa);

    if (baker.vertexCount() > maxVertices) maxVertices = baker.vertexCount();
    if (baker.batches().size() > maxBatches) maxBatches = baker.batches().size();

    // The baker's own invariants: every batch's range must sit inside the
    // arrays, and every index must sit inside its own batch.
    for (const sscore::SsBatchDesc& d : baker.batches()) {
      if (d.vertexOffset + d.vertexCount > static_cast<int32_t>(baker.vertexCount())) {
        Fail("bake.vertexRange", d.vertexOffset + d.vertexCount,
             static_cast<long long>(baker.vertexCount()), frame, 0);
      }
      for (int32_t i = 0; i < d.indexCount; ++i) {
        const uint16_t v = baker.indices()[d.indexOffset + i];
        if (v >= d.vertexCount) {
          Fail("bake.index", v, d.vertexCount, frame, static_cast<int>(i));
          break;
        }
      }
    }
  }

  ss_runtime_destroy(ctx);
  ss_resource_destroy(resource);

  if (g_failures > 0) {
    std::fprintf(stderr, "\nFAILED: %d mismatches over %d frames\n", g_failures, frames);
    return 1;
  }
  std::printf("OK: %d frames, peak %zu vertices / %zu batches\n", frames, maxVertices, maxBatches);
  return 0;
}
